import {chromium} from 'playwright';
import {writeFileSync} from 'node:fs';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1280,height:720},recordVideo:{dir:'.work/browser',size:{width:1280,height:720}},reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const ready=()=>page.locator('[data-layout-ready]').waitFor();
const pause=ms=>page.waitForTimeout(ms);
await page.goto('http://127.0.0.1:4333/book-notes/');await ready();await pause(800);
await page.getByRole('combobox',{name:'Architecture',exact:true}).selectOption('litefleet');await ready();await pause(1000);
await page.getByRole('link',{name:'Open detail for Litefleet',exact:true}).click();await ready();await pause(800);
await page.getByRole('link',{name:'Open detail for Gateway',exact:true}).click();await ready();
await page.getByRole('button',{name:'Fit View',exact:true}).click();
await page.locator('[data-layout-ready]').scrollIntoViewIfNeeded();await pause(1200);
await page.locator('[data-layout-ready]').screenshot({path:'public/diagram.png'});
await page.screenshot({path:'evidence/browser-final.png'});
const heading=await page.getByRole('heading',{level:1}).textContent();
if(!page.url().endsWith('/gateway-components')||!heading.includes('gateway components')||errors.length)throw Error(JSON.stringify({heading,errors,url:page.url()}));
await pause(1600);
const video=page.video();await context.close();await video.saveAs('public/browser.webm');await browser.close();
writeFileSync('evidence/browser.json',JSON.stringify({heading,errors,url:page.url(),viewport:'1280x720',workflow:['open catalog','select Litefleet','open containers','open gateway components','Fit View'],mockedRequests:false},null,2));
